export function companyOfProvider(provider: string): string {
  return PROVIDER_COMPANY[String(provider || '').toLowerCase()] || '';
}

export function CompanyMark(props: { provider?: string; company?: string }) {
  const company = props.company || companyOfProvider(props.provider || '');
  const icon = ICONS[company];
  if (!icon) return null;
  return (
    <svg
      className="model-icon"
      data-mark={icon.mark}
      viewBox={icon.viewBox}
      aria-hidden="true"
    >
      <path fill="currentColor" d={icon.d} />
    </svg>
  );
}

export function windowAbbrev(name: string): string {
  const n = String(name || '').toLowerCase();
  if (n === 'session') return 's';
  if (n === 'weekly') return 'w';
  if (n === 'monthly') return 'm';
  return n ? n.charAt(0) : '?';
}
